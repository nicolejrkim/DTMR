"""Runnable demos that need no dataset download.

    python -m dtmr.demo list
    python -m dtmr.demo prepare [NAME ...]      build the reference motions under ./data
    python -m dtmr.demo run NAME [--smoke] [--output_dir DIR] [tracker flags ...]

Every demo pairs a reference builder with one of the example configs.  The
references are generated by the handcrafted G1 generators (no download).
`--smoke` shrinks the sampler (Nsample 256, Ndiffuse 2, 20 steps) to check the
install in about a minute; drop it for the tuned run described in the config header.
"""
from __future__ import annotations

import argparse
import os
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

import yaml

from dtmr.utils import get_example_path

SMOKE_OVERRIDES = {"Nsample": 256, "Ndiffuse": 2, "Ndiffuse_init": 2, "n_steps": 20}


@dataclass(frozen=True)
class Demo:
    name: str
    config: str                 # example config file name
    reference: Path             # what the config's motion_path points at (relative to the cwd)
    build: tuple[str, ...]      # `python -m <module> <args...>` that writes it
    about: str



DEMOS = [
    Demo("g1_jump", "unitree_g1_jump_handcrafted_warp.yaml",
         Path("data/handcrafted/hc_jump_50Hz.npz"),
         ("dtmr.data.handcrafted.jump_g1", "--out-dir", "data/handcrafted"),
         "G1 three consecutive standing broad jumps (handcrafted, 0.8 m each)"),
    Demo("g1_sprint", "unitree_g1_sprint_handcrafted_warp.yaml",
         Path("data/handcrafted/hc_sprint_50Hz.npz"),
         ("dtmr.data.handcrafted.sprint_g1", "--out-dir", "data/handcrafted"),
         "G1 sprint at 3 m/s with flight phases (handcrafted)"),
    Demo("g1_triplejump", "unitree_g1_triplejump_handcrafted_warp.yaml",
         Path("data/handcrafted/hc_triplejump_50Hz.npz"),
         ("dtmr.data.handcrafted.triplejump_g1", "--out-dir", "data/handcrafted"),
         "G1 run-up, hop, step, jump (handcrafted competition triple jump)"),
    Demo("g1_home_hold", "unitree_g1_home_hold_warp.yaml",
         Path("data/home_hold/home_hold_50Hz.npz"),
         ("dtmr.data.build_home_hold_reference", "--robot", "unitree_g1",
          "--out-dir", "data/home_hold"),
         "G1 standing still (the home keyframe held for 20 s); a sanity check, not a showcase"),
]
BY_NAME = {d.name: d for d in DEMOS}


def _run_module(module: str, *args: str) -> None:
    cmd = [sys.executable, "-m", module, *args]
    print("[demo] $", " ".join(cmd))
    subprocess.run(cmd, check=True)


def cmd_list(_: argparse.Namespace) -> None:
    width = max(len(d.name) for d in DEMOS)
    for d in DEMOS:
        state = "ready" if d.reference.exists() else "needs prepare"
        print(f"  {d.name:<{width}}  {state:<14} {d.about}")


def cmd_prepare(args: argparse.Namespace) -> None:
    names = args.names or [d.name for d in DEMOS]
    for name in names:
        d = BY_NAME[name]
        if d.reference.exists() and not args.force:
            print(f"[demo] {name}: {d.reference} exists, skipping (--force to rebuild)")
            continue
        _run_module(*d.build)
        if not d.reference.exists():
            sys.exit(f"[demo] {name}: builder finished but {d.reference} is missing")
        print(f"[demo] {name}: wrote {d.reference}")


def cmd_run(args: argparse.Namespace) -> None:
    d = BY_NAME[args.name]
    if not d.reference.exists():
        sys.exit(f"[demo] {args.name}: {d.reference} missing; run `python -m dtmr.demo prepare {args.name}`")
    config = str(get_example_path(d.config))
    output_dir = args.output_dir or f"output/demo_{args.name}"
    if args.smoke:
        os.makedirs(output_dir, exist_ok=True)
        config_path = Path(output_dir) / "smoke_config.yaml"
        with open(config_path, "w") as f:
            f.write("# smoke profile written by `python -m dtmr.demo run --smoke`\n")
            yaml.safe_dump({"base_config": config, **SMOKE_OVERRIDES}, f, sort_keys=False)
        config = str(config_path)
    from dtmr.tracker.cli import main as tracker_main
    sys.argv = ["dtmr", "--config", config, "--output_dir", output_dir, "--no_viz", "--no_serve", *args.tracker_args]
    print("[demo] $", " ".join(sys.argv))
    tracker_main()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("list", help="show the demos and whether their references exist").set_defaults(func=cmd_list)
    p = sub.add_parser("prepare", help="build the reference motion(s) under ./data")
    p.add_argument("names", nargs="*", choices=[*BY_NAME, []], help="default: all")
    p.add_argument("--force", action="store_true", help="rebuild even if the reference exists")
    p.set_defaults(func=cmd_prepare)
    p = sub.add_parser("run", help="track one demo with its example config")
    p.add_argument("name", choices=list(BY_NAME))
    p.add_argument("--smoke", action="store_true", help=f"tiny sampler for an install check: {SMOKE_OVERRIDES}")
    p.add_argument("--output_dir", default=None, help="default: output/demo_<name>")
    p.epilog = "Unrecognised flags are passed to the tracker CLI (e.g. --n_steps 100 --seed 1)."
    p.set_defaults(func=cmd_run)
    args, extra = parser.parse_known_args()
    if extra and args.command != "run":
        parser.error(f"unrecognised arguments: {' '.join(extra)}")
    args.tracker_args = extra
    args.func(args)


if __name__ == "__main__":
    main()
